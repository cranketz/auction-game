export function scoreBreakfast(selected) {
 const unique=[...new Map(selected.map(x=>[x.modelId,x])).values()];
 const ids=new Set(unique.map(x=>x.modelId));
 const items=unique.map(x=>({name:x.name,points:x.basic?8:4}));
 const base=items.reduce((s,x)=>s+x.points,0);
 const complete=['Ekmek','Peynir','Yumurta','İçecek'].every(g=>unique.some(x=>x.group===g));
 const completeness=complete?12:0;
 const diversity=Math.min(4,new Set(unique.filter(x=>!x.basic).map(x=>x.group)).size)*2;
 const pairs=PAIRS.filter(pair=>pair.every(id=>ids.has(id))).map(pair=>({name:pair.map(id=>BREAKFAST.find(x=>x.modelId===id).name).join(' + '),points:4}));
 const pairPoints=Math.min(24,pairs.length*4);
 const triples=TRIPLES.filter(t=>t.ids.every(id=>ids.has(id))).map(t=>({name:t.name,points:8}));
 const triplePoints=Math.min(2,triples.length)*8;
 return {points:base+completeness+diversity+pairPoints+triplePoints,complete,breakdown:{items,base,completeness,diversity,pairs,pairPoints,triples,triplePoints,duplicates:selected.length-unique.length}};
}
